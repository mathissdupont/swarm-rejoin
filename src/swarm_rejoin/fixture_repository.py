"""A signed in-memory repository and deterministic transport for tests/demo.

Ed25519 private keys are generated by the cryptographic library, held in memory,
and never serialized. The transport models I/O; signatures/hashes are real TUF.
This is neither a production repository publisher nor an identity protocol.
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone
import hashlib
import json
from typing import Iterator
from urllib.parse import urlsplit

from securesystemslib.signer import CryptoSigner
from tuf.api.exceptions import DownloadHTTPError
from tuf.api.metadata import Metadata, MetaFile, Root, Snapshot, TargetFile, Targets, Timestamp
from tuf.ngclient.fetcher import FetcherInterface


def release_fields(release_id: str, epoch: int = 1, **changes: object) -> dict:
    result = {
        "schema_version": 1, "release_id": release_id, "security_epoch": epoch,
        "component": "mission-app", "platform": "companion-model-v1",
        "protocol": "swarm-v1", "data_schema": "data-v1",
        "activation_profile": "modeled-ground-v1", "health_profile": "fixture-health-v1",
    }
    result.update(changes)
    return result


class FixtureFetcher(FetcherInterface):
    def __init__(self, routes: dict[str, bytes]):
        self.routes = routes
        self.truncate_targets = False
        self.target_requests = 0

    def _fetch(self, url: str) -> Iterator[bytes]:
        parsed = urlsplit(url)
        if parsed.scheme != "https" or parsed.netloc != "repository.invalid" or parsed.query or parsed.fragment:
            raise DownloadHTTPError("Unknown fixture origin", 404)
        data = self.routes.get(parsed.path)
        if data is None:
            raise DownloadHTTPError("No such fixture file", 404)
        if parsed.path.startswith("/targets/"):
            self.target_requests += 1
            if self.truncate_targets:
                data = data[:len(data) // 2]
        yield data


class SignedFixtureRepository:
    def __init__(self):
        self.created_at = datetime.now(timezone.utc)
        self.signers = {name: CryptoSigner.generate_ed25519() for name in (
            "root", "targets", "snapshot", "timestamp"
        )}
        root = Root(expires=self.created_at + timedelta(days=7), consistent_snapshot=True)
        for role, signer in self.signers.items():
            root.add_key(signer.public_key, role)
        self.bootstrap = self._signed(root, "root")
        self.routes: dict[str, bytes] = {}
        self.fetcher = FixtureFetcher(self.routes)
        self.packages: dict[str, tuple[bytes, dict]] = {}

    def _signed(self, data: object, role: str) -> bytes:
        metadata = Metadata(data)
        metadata.sign(self.signers[role])
        return metadata.to_bytes()

    def add(self, target: str, payload: bytes, custom: dict) -> None:
        self.packages[target] = (payload, custom)

    def publish(self, version: int = 1, *, expires: datetime | None = None) -> None:
        expiry = expires if expires is not None else self.created_at + timedelta(days=1)
        targets = Targets(version=version, expires=expiry)
        self.routes["/metadata/1.root.json"] = self.bootstrap
        for target, (payload, custom) in self.packages.items():
            info = TargetFile.from_data(target, payload, ["sha256"])
            info.unrecognized_fields["custom"] = custom
            targets.targets[target] = info
            digest = hashlib.sha256(payload).hexdigest()
            self.routes[f"/targets/{digest}.{target}"] = payload
        target_bytes = self._signed(targets, "targets")
        snapshot = Snapshot(version=version, expires=expiry, meta={
            "targets.json": MetaFile.from_data(version, target_bytes, ["sha256"])
        })
        snapshot_bytes = self._signed(snapshot, "snapshot")
        timestamp = Timestamp(version=version, expires=expiry,
                              snapshot_meta=MetaFile.from_data(version, snapshot_bytes, ["sha256"]))
        self.routes[f"/metadata/{version}.targets.json"] = target_bytes
        self.routes[f"/metadata/{version}.snapshot.json"] = snapshot_bytes
        self.routes["/metadata/timestamp.json"] = self._signed(timestamp, "timestamp")

    def export_public(self) -> dict:
        """Only public metadata, opaque demo payloads and the provisioned root."""
        return {"bootstrap": json.loads(self.bootstrap), "files": {
            path: data.decode("utf-8") for path, data in sorted(self.routes.items())
        }}
